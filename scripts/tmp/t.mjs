import { chromium } from 'playwright';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1200, height: 900 }, deviceScaleFactor: 2 });
const errs=[]; page.on('pageerror', e=>errs.push(e.message));
await page.goto('http://localhost:5173/admin', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(3000);
const txt = await page.locator('body').innerText();
console.log('퍼즐력 재계산 섹션:', txt.includes('퍼즐력 재계산') ? '있음' : '없음');
console.log('규모 확인 버튼:', await page.getByRole('button', { name: '규모 확인' }).count());
const apply = page.getByRole('button', { name: '반영' });
console.log('반영 버튼:', await apply.count(), '| 비활성:', await apply.count() ? await apply.isDisabled() : 'n/a');
await page.screenshot({ path: 'scripts/tmp/admin.png', clip: { x: 0, y: 0, width: 340, height: 320 } });
console.log('에러:', errs.length ? errs.slice(0,2) : '없음');
await b.close();
