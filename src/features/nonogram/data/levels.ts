export interface NonogramLevel {
  id: string;
  name: string;
  /** 배경(빈 칸) 색상 — 완성 연출 시 빈 칸이 이 색으로 채워짐 */
  background: string;
  /** 문자 → 색상. '.'은 배경이므로 포함하지 않음 */
  palette: Record<string, string>;
  /**
   * 퍼즐에서는 "빈 칸"이지만 완성 시 palette 색으로 칠해지는 문자들.
   * 예: 판다 얼굴의 흰색 — 검정만 채우고 흰 부분은 비워두는 퍼즐
   */
  emptyChars?: string;
  /**
   * 난이도. 'hard' 는 줄 논리만으로는 막히는 구간이 있어 가정(추측)이 필요한 퍼즐.
   * 답은 여전히 유일하므로 어떻게 채워도 정답과 일치한다. 생략하면 'normal'.
   */
  difficulty?: 'normal' | 'hard';
  /** 행별 문자열. '.' = 배경(빈 칸), emptyChars = 빈 칸, 그 외 문자 = 채움 */
  art: string[];
  /**
   * 완성 연출 뒤 픽셀아트 위로 페이드인되는 고해상도 일러스트 (public 경로).
   * 없으면 픽셀아트만 보여준다.
   */
  image?: string;
}

