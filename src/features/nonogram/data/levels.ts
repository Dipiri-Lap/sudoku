function isFilled(level: NonogramLevel, ch: string): boolean {
  if (ch === '.') return false;
  return !(level.emptyChars ?? '').includes(ch);
}

/** art 문자열에서 정답 그리드(1 = 채움, 0 = 빈 칸) 생성 */
export function solutionGrid(level: NonogramLevel): number[][] {
  return level.art.map(row => [...row].map(ch => (isFilled(level, ch) ? 1 : 0)));
}

/** 각 칸의 완성 색상 (배경 문자는 배경색) */
export function artColors(level: NonogramLevel): string[][] {
  return level.art.map(row => [...row].map(ch => (ch === '.' ? level.background : level.palette[ch] ?? '#23303f')));
}

/** 한 줄(행 또는 열)의 연속된 채움 블록 길이 목록. 빈 줄이면 [0] */
export function lineClues(line: number[]): number[] {
  const clues: number[] = [];
  let run = 0;
  for (const v of line) {
    if (v === 1) run++;
    else if (run > 0) { clues.push(run); run = 0; }
  }
  if (run > 0) clues.push(run);
  return clues.length ? clues : [0];
}

export function buildClues(grid: number[][]) {
  const rows = grid.map(lineClues);
  const cols = grid[0].map((_, c) => lineClues(grid.map(row => row[c])));
  return { rows, cols };
}
