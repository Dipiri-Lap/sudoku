/**
 * 게임 설명 페이지(/guide) 콘텐츠.
 * 규칙·수치는 각 게임 코드 기준이다. 게임 쪽을 바꾸면 여기도 같이 고칠 것.
 */

export interface GuideShot {
  src: string;
  caption: string;
}

export interface GuideSection {
  /** 작은 라벨 (예: "기본 규칙") */
  label: string;
  title: string;
  /** 문단 배열 */
  body: string[];
  /** 불릿 목록 (선택) */
  bullets?: string[];
  /** 실제 플레이 화면 캡처 (SHOTS 맵에서 채워진다) */
  shots?: GuideShot[];
}

export interface GuideGame {
  id: string;
  /** 플레이 경로 */
  playPath: string;
  name: string;
  /** 한 줄 소개 */
  tagline: string;
  /** 타이틀 이미지 (목록 카드) */
  image: string;
  /** 대표 플레이 화면 (상세 히어로) — SHOTS 맵에서 채워진다 */
  hero?: string;
  /** 포인트 색 */
  color: string;
  /** 목록 카드에 보일 태그 */
  tags: string[];
  /** 한눈에 보기 */
  facts: { k: string; v: string }[];
  sections: GuideSection[];
  tips: string[];
  faq: { q: string; a: string }[];
}

