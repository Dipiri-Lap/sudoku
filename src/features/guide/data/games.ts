export const GUIDE_GAMES: GuideGame[] = RAW_GAMES.map(g => {
  const m = SHOTS[g.id] ?? {};
  const path = (name: string) => `/images/guide/${g.id}/${name}.webp`;
  return {
    ...g,
    hero: m._hero ? path(m._hero[0][0]) : undefined,
    sections: g.sections.map(s => ({
      ...s,
      shots: m[s.label]?.map(([name, caption]) => ({ src: path(name), caption })),
    })),
  };
});

export const getGuideGame = (id: string | undefined) => GUIDE_GAMES.find(g => g.id === id);
